export interface Province {
  id: string;
  name: string;
  code: string;
  population: number;
  activeCases: number;
  totalHistoricalCases: number;
  curedCases: number;
  incidenceRatePer100k: number;
  riskLevel: 'Crítico' | 'Moderado' | 'Baixo';
}

export interface Locality {
  id: string;
  provinceId: string;
  name: string;
  population: number;
  activeCases: number;
  curedCases: number;
  mdrCases: number;
  incidenceRatePer100k: number;
  riskLevel: 'Alto' | 'Moderado' | 'Baixo';
}

export interface HealthPost {
  id: string;
  name: string;
  code: string;
  provinceId: string;
  localityId: string;
  type: 'Hospital Central / Provincial' | 'Hospital Geral / Rural' | 'Centro de Saúde' | 'Posto TB Comunitário' | 'Dispensário Especializado';
  address: string;
  phone: string;
  technicalLead: string;
  genexpertAvailable: boolean;
  microscopyAvailable: boolean;
  medicineStockLevel: 'Adequado' | 'Aviso (Baixo)' | 'Crítico (Esgotado)';
  assignedPatientsCount: number;
}

export type TBType = 'Pulmonar Smear+' | 'Pulmonar Smear-' | 'Extrapulmonar' | 'Multirresistente (MDR)';
export type PatientStatus = 'Em Tratamento' | 'Suspeito' | 'Curado' | 'Abandono' | 'Óbito';
export type TreatmentPhase = 'Fase Intensiva (2RHZE)' | 'Fase de Manutenção (4RH)' | 'Tratamento MDR (18-24M)' | 'Regime Curto Oral MDR (9-11M)' | 'Concluído' | 'Não Iniciado';

export interface Consultation {
  id: string;
  patientId: string;
  date: string; // YYYY-MM-DD
  doctorOrNurse: string;
  weightKg: number;
  symptoms: string;
  clinicalNotes: string;
  treatmentAdherence: 'Excelente (>95%)' | 'Regular (80-95%)' | 'Irregular (<80%)';
  nextAppointmentDate?: string;
}

export interface Exam {
  id: string;
  patientId: string;
  date: string; // YYYY-MM-DD
  type: 'Baciloscopia (BK)' | 'GeneXpert MTB/RIF' | 'Raio-X de Tórax (RX)' | 'Cultura / Antibiograma' | 'Hemograma / Bioquímica' | 'Teste HIV';
  result: string;
  laboratory: string;
  attachmentName?: string;
  notes?: string;
}

export interface Patient {
  id: string;
  code: string;
  name: string;
  age: number;
  gender: 'Masculino' | 'Feminino';
  identityDoc: string;
  phone: string;
  address: string;
  provinceId: string;
  localityId: string;
  healthPostId: string;
  tbType: TBType;
  status: PatientStatus;
  treatmentPhase: TreatmentPhase;
  startDate: string; // YYYY-MM-DD
  dotsSupervised: boolean;
  contactTracingCount: number;
  comorbidities: string[]; // e.g. ["HIV", "Diabetes", "Desnutrição", "Hipertensão"]
  sputumSmearResult: 'Positivo (+++)' | 'Positivo (++)' | 'Positivo (+)' | 'Negativo' | 'Pendente';
  notes?: string;
  consultations?: Consultation[];
  exams?: Exam[];
}

